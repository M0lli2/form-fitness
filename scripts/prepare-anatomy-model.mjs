/** Convert the full attribution-bearing GLB to compact indexed surfaces for the native guide. */
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const [source, output, simplifier] = process.argv.slice(2);
if (!source || !output || !simplifier) throw new Error('Usage: node scripts/prepare-anatomy-model.mjs source.glb src/anatomy-sculpt-data.mjs meshopt_simplifier.cjs');
const {default: MeshoptSimplifier} = await import(pathToFileURL(path.resolve(simplifier)));
await MeshoptSimplifier.ready;
const glb = fs.readFileSync(source);
const jsonLength = glb.readUInt32LE(12);
const document = JSON.parse(glb.toString('utf8',20,20+jsonLength));
const binaryStart = 28+jsonLength;
if (glb.toString('ascii',0,4)!=='glTF'||document.meshes.length!==16) throw new Error('Expected the Form sculpture GLB');
// The independent ZBrush subtools keep their boundaries through simplification.
const faceBudget=[850,600,950,370,860,530,990,630,610,420,490,700,490,230,600,760];
const chunks=[];
const header=Buffer.alloc(2); header.writeUInt16LE(document.meshes.length); chunks.push(header);
let meshFaces=0,meshVertices=0;
for (const [part,{primitives:[primitive]}] of document.meshes.entries()) {
  function readAccessor(index) {
    const accessor=document.accessors[index], view=document.bufferViews[accessor.bufferView];
    return {count:accessor.count,offset:binaryStart+(view.byteOffset??0)+(accessor.byteOffset??0)};
  }
  const points=readAccessor(primitive.attributes.POSITION);
  const normals=readAccessor(primitive.attributes.NORMAL);
  const originals=readAccessor(primitive.indices);
  const positions=Float32Array.from({length:points.count*3},(_,i)=>glb.readFloatLE(points.offset+i*4));
  const indices=Uint16Array.from({length:originals.count},(_,i)=>glb.readUInt16LE(originals.offset+i*2));
  // Error-bounded indexed simplification preserves muscle silhouettes and avoids cracks
  // from merging unrelated surfaces that happen to fall inside the same spatial cell.
  const [reduced]=MeshoptSimplifier.simplify(indices,positions,3,faceBudget[part]*3,.075);
  const remap=new Map(), vertices=[], faces=[];
  for(const original of reduced){
    let packed=remap.get(original);
    if(packed===undefined){
      packed=vertices.length;
      remap.set(original,packed);
      const start=original*3;
      vertices.push([...positions.subarray(start,start+3),
        ...[0,1,2].map(k=>glb.readFloatLE(normals.offset+original*12+k*4))]);
    }
    faces.push(packed);
  }
  meshFaces+=faces.length/3; meshVertices+=vertices.length;
  const group=Buffer.alloc(4+vertices.length*9+faces.length*2);
  group.writeUInt16LE(vertices.length,0);
  group.writeUInt16LE(faces.length/3,2);
  for(const [i,v] of vertices.entries()){
    const offset=4+i*9, normalLength=Math.hypot(v[3],v[4],v[5])||1;
    for(let k=0;k<3;k++){
      group.writeInt16LE(Math.round(10000*v[k]),offset+2*k);
      group.writeInt8(Math.round(127*v[k+3]/normalLength),offset+6+k);
    }
  }
  for(const [i,index] of faces.entries()) group.writeUInt16LE(index,4+vertices.length*9+2*i);
  chunks.push(group);
}
const bundle=Buffer.concat(chunks);
const lines=bundle.toString('base64').match(/.{1,112}/g);
fs.writeFileSync(output,"// Generated by scripts/prepare-anatomy-model.mjs. Source: Diego Luján García, CC BY 4.0.\nexport const sculptureData = [\n  '"+lines.join("',\n  '")+"',\n].join('');\n");
console.log(JSON.stringify({meshFaces,meshVertices,bytes:bundle.length}));


